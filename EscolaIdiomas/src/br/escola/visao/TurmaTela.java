 private void executarBusca(String termo) {
    if (termo == null || termo.trim().isEmpty() || 
        termo.equals("Buscar por Nome, ID ou Idioma...") || 
        termo.equals("Filtro por ID ou Idioma")) {
        carregarTabelaTurmas();
        return;
    }
 
    // Usa o modelo já existente da tabela em vez de criar um novo do zero
    DefaultTableModel modelo = (DefaultTableModel) jTableTurma.getModel();
    modelo.setRowCount(0); // Limpa as linhas atuais
 
    List<Turma> lista = turmaController.listarTurmas();
    if (lista != null) {
        String busca = termo.toLowerCase().trim();
 
        for (Turma t : lista) {
            // Tratamento de nulos para evitar NullPointerException
            String idStr = String.valueOf(t.getIdTurma());
            String nomeStr = t.getNomeTurma() != null ? t.getNomeTurma().toLowerCase() : "";
            
            // Ajusta o getter do idioma conforme o teu modelo (ex: t.getIdioma() ou t.getNomeIdioma())
            String idiomaStr = t.getIdioma() != null ? t.getIdioma().toLowerCase() : ""; 
            String profStr = t.getProfessor() != null ? t.getProfessor().toLowerCase() : "";
 
            // Verifica se o termo bate com algum dos campos
            if (idStr.contains(busca) || nomeStr.contains(busca) || idiomaStr.contains(busca) || profStr.contains(busca)) {
                
                modelo.addRow(new Object[]{
                    t.getIdTurma(),
                    t.getNomeTurma(),
                    t.getIdioma(),
                    t.getHorario(),
                    t.getProfessor(),
                    t.getAlunosMatriculados() // Ou 0 se não tiveres este getter
                });
            }
        }
    }
}
        private void carregarTabelaTurmas() {
 
    DefaultTableModel modelo = (DefaultTableModel) jTableTurma.getModel();
        modelo.setRowCount(0);
 
        List<Turma> lista = turmaController.listarTurmas();
        if (lista != null) {
            for (Turma t : lista) {
                modelo.addRow(new Object[]{
                    t.getIdTurma(),
                    t.getNomeTurma(),
                    t.getIdioma(),
                    t.getHorario(),
                    t.getProfessor(),
                    t.getAlunosMatriculados()
                });
            }
        }
    }
        private void carregarTabelaRelatorio() {
        DefaultTableModel modelo = (DefaultTableModel) jTableRelatorio.getModel();
        modelo.setColumnIdentifiers(new Object[]{"ID Turma", "Turno", "Sala", "Idioma", "Total Alunos"});
        modelo.setRowCount(0);
 
        RelatorioDAO dao = new RelatorioDAO();
        List<Object[]> dados = dao.obterRelatorioConsolidado();
 
        if (dados != null) {
            for (Object[] linha : dados) {
                modelo.addRow(linha);
            }
        }
        
        }
 
    private void limparCampos() {
        txtId.setText("");
        txtNomeTurma.setText("");
        cbIdioma.setSelectedIndex(0);
        cbHorario.setSelectedIndex(0);
        cbProfessor.setSelectedIndex(0);
        jTableTurma.clearSelection();
    }
 
