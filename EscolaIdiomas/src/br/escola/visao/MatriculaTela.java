private void carregarTabelaMatriculas() {
    DefaultTableModel modelo = (DefaultTableModel) jTableMatricula.getModel();
    modelo.setRowCount(0);
 
    List<Matricula> lista = matriculaController.listarMatriculas();
    if (lista != null) {
        for (Matricula m : lista) {
            modelo.addRow(new Object[]{
                m.getIdMatricula(),
                m.getIdAluno(),
                m.getIdTurma(),
                m.getDataMatricula(),
                m.getStatusMatricula()
            });
        }
    }
}
 
   private void limparCampos() {
    txtId.setText("");
    txtIdAluno.setText("");
    txtIdTurma.setText("");
    cbStatus.setSelectedIndex(0);
    jTableMatricula.clearSelection();
}
   private void carregarTabelaRelatorio() {
    DefaultTableModel modelo = (DefaultTableModel) jTableRelatorio.getModel();
    
    // Define os cabeçalhos correspondentes à VIEW do MySQL
    modelo.setColumnIdentifiers(new Object[]{"ID Turma", "Turno", "Sala", "Idioma", "Total Alunos"});
    modelo.setRowCount(0);
    
    RelatorioDAO dao = new RelatorioDAO();
    List<Object[]> dados = dao.obterRelatorioConsolidado();
    
    for (Object[] linha : dados) {
        modelo.addRow(linha);
    }
   
   }

    
    
