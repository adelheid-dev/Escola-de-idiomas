    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
       String nome = txtNomeIdioma.getText();
        if (controller.salvar(nome, "Ativo")) {
            limparCampos();
        }
    }//GEN-LAST:event_btnInserirActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        controller.pesquisar(txtPesquisa.getText(), modeloTabela);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void jTableIdiomasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableIdiomasMouseClicked
       int linha = jTableIdiomas.getSelectedRow();
        if (linha != -1) {
            txtId.setText(jTableIdiomas.getValueAt(linha, 0).toString());
            txtNomeIdioma.setText(jTableIdiomas.getValueAt(linha, 1).toString());
        }
    }//GEN-LAST:event_jTableIdiomasMouseClicked
       
    private void limparCampos() {
        txtId.setText("");
        txtNomeIdioma.setText("");
        txtPesquisa.setText("");
        controller.carregarTabela(modeloTabela);
    }
