   private void carregarTabelaAlunos() {
        DefaultTableModel modelo = (DefaultTableModel) jTableAlunos.getModel();
        modelo.setColumnIdentifiers(new Object[]{ "ID", "CPF", "E-mail", "Telefone", "Data de Matrícula", "Situação" });
        modelo.setRowCount(0);

        try {
            List<Aluno> lista = controller.listarAlunos();

            if (lista != null) {
                for (Aluno a : lista) {
                    modelo.addRow(new Object[]{
                        a.getIdPessoa(),
                        a.getCpf(),
                        a.getEmail(),
                        a.getTelefone() != null ? a.getTelefone() : "",
                        a.getDataMatriculaInicial() != null ? a.getDataMatriculaInicial().format(formatter) : "",
                        a.getSituacao()
                    });
                }
            }
        } catch (Exception e) {
            mostrarErro(e);
        }
    }

    private void carregarTabelaFinanceiro() {
        DefaultTableModel modelo = (DefaultTableModel) jTableFinanceiro.getModel();
        modelo.setColumnIdentifiers(new Object[]{ "ID Pagamento", "ID Aluno", "ID Turma", "Valor (R$)", "Data", "Forma Pagamento", "Status" });
        modelo.setRowCount(0);

        try {
            FinanceiroDAO dao = new FinanceiroDAO();
            List<Financeiro> lista = dao.listarTodos();

            if (lista != null) {
                for (Financeiro f : lista) {
                    modelo.addRow(new Object[]{
                        f.getIdPagamento(),
                        f.getIdAluno(),
                        f.getIdTurma(),
                        String.format("%.2f", f.getValor()),
                        f.getDataPagamento() != null ? f.getDataPagamento().format(formatter) : "",
                        f.getFormaPagamento(),
                        f.getStatus()
                    });
                }
            }
        } catch (Exception e) {
            mostrarErro(e);
        }
    }

