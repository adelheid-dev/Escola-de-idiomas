    /** Lê o formulário de aluno (a validação fica no controller). */
    private Aluno lerFormularioAluno() {
        Aluno a = new Aluno();
        a.setNome(txtNomel.getText().trim());
        a.setCpf(txtCpf.getText().trim());
        a.setEmail(txtEmaill.getText().trim());
        a.setTelefone(txtTelefonel.getText().trim());
        a.setSituacao(cbSituacaol.getSelectedItem().toString().trim());
        if (!txtDataNascimento.getText().replace("/", "").trim().isEmpty()) {
            a.setDataNascimento(LocalDate.parse(txtDataNascimento.getText().trim(), formatter));
        }
        return a;
    }

    /** Mostra mensagem compreensível, nunca a exceção bruta do driver (B1). */
    private void mostrarErro(Exception e) {
        String m;
        if (e instanceof SQLException) {
            m = TradutorErroBD.traduzir((SQLException) e);
        } else if (e instanceof DateTimeParseException) {
            m = "Data inválida. Use o formato dd/MM/aaaa.";
        } else if (e instanceof NumberFormatException) {
            m = "Informe números válidos (IDs e valor).";
        } else if (e instanceof IllegalArgumentException) {
            m = e.getMessage();
        } else {
            e.printStackTrace();
            m = "Ocorreu um erro inesperado.";
        }
        JOptionPane.showMessageDialog(this, m, "Atenção", JOptionPane.WARNING_MESSAGE);
    }

    /** A matrícula é identificada por (id_aluno, id_turma): o campo aceita "aluno/turma", ex.: 1/9. */
    private int[] lerAlunoTurma() {
        String[] p = txtIdMatricula.getText().trim().split("[/\\-,;\\s]+");
        if (p.length != 2) {
            throw new IllegalArgumentException("Informe o aluno e a turma no formato ID do aluno/ID da turma. Exemplo: 1/9");
        }
        return new int[]{ Integer.parseInt(p[0]), Integer.parseInt(p[1]) };
    }

    /** Lê o formulário do financeiro. Pendente/Atrasado ficam sem data de pagamento (NULL). */
    private Financeiro lerFormularioFinanceiro() {
        Financeiro f = new Financeiro();
        int[] chave = lerAlunoTurma();
        f.setIdAluno(chave[0]);
        f.setIdTurma(chave[1]);
        f.setValor(Double.parseDouble(txtValor.getText().trim().replace(",", ".")));
        f.setFormaPagamento(cbFormaPagamento.getSelectedItem().toString().trim());
        f.setStatus(cbStatus.getSelectedItem().toString().trim());
        if (!jFDataPagamento.getText().replace("/", "").trim().isEmpty()) {
            f.setDataPagamento(LocalDate.parse(jFDataPagamento.getText().trim(), formatter));
        } else if ("Pago".equals(f.getStatus())) {
            f.setDataPagamento(LocalDate.now());
        }
        return f;
    }

