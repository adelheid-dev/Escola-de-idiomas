    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
      String termo = txtBuscal.getText().trim();
        if (termo.isEmpty() || termo.equals("Busca  por Nome,CPF ou ID..")) {
            carregarTabelaAlunos();
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) jTableAlunos.getModel();
        modelo.setRowCount(0);

        try {
            List<Aluno> lista = controller.pesquisarAlunos(termo);

            for (Aluno a : lista) {
                modelo.addRow(new Object[]{
                    a.getIdPessoa(),
                    a.getCpf(),
                    a.getEmail(),
                    a.getTelefone(),
                    a.getDataMatriculaInicial() != null ? a.getDataMatriculaInicial().format(formatter) : "",
                    a.getSituacao()
                });
            }
        } catch (Exception e) {
            mostrarErro(e);
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

